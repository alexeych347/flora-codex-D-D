import { PrismaClient } from '@prisma/client';
import { upsertPlayers } from './players';

const prisma = new PrismaClient();

async function main() {
  await prisma.herbAccess.deleteMany();
  await prisma.herb.deleteMany();

  const players = await upsertPlayers(prisma);
  console.log(`✓ Игроки созданы/обновлены: ${players.map((p) => p.name).join(', ')}`);
  const playerIds = players.filter((p) => p.role === 'PLAYER').map((p) => p.id);

  const mint = await prisma.herb.create({
    data: {
      name: 'Серебристая Мята',
      latinName: 'Mentha argentum',
      rarity: 'COMMON',
      discoveredAt: '15-й день месяца Урожая, 1247 год',
      description:
        'Эту скромную травку впервые описала деревенская травница Агата из Миствейла — добрая старушка, что всю жизнь лечила местных крестьян да их скот. Говорят, мята росла у неё прямо под окном, серебрясь на рассвете от утренней росы. После её смерти рецепт передавался из рук в руки, пока не попал в руки странствующих знахарей. Старики говорят, что тот, кто испробует отвар из этой травы в полнолуние, увидит во сне своих предков.',
      properties: ['Лечебная', 'Успокаивающая'],
      effects:
        'Восстанавливает 1d4 HP при приёме. Снимает эффект Отравления. При заваривании в горячей воде даёт успокоительный отвар — цель имеет преимущество на спасброски от Испуга в течение 1 часа.',
      sortOrder: 1,
    },
  });

  const nightshade = await prisma.herb.create({
    data: {
      name: 'Пепельный Паслён',
      latinName: 'Solanum cinerum',
      rarity: 'RARE',
      discoveredAt: '3-й день месяца Теней, 1251 год',
      description:
        'Запрещённая к обороту во многих государствах, эта трава была любимым инструментом Ордена Пепельного Пламени — братства алхимиков, уничтоженного инквизицией полвека назад. Растёт только на пепелищах и местах массовых захоронений, впитывая в себя остаточную некротическую энергию. Тёмно-серые ягоды мерцают в темноте слабым синеватым светом. Говорят, что алхимики Ордена умели разговаривать с духами, используя дым от сожжённых листьев этого растения.',
      properties: ['Ядовитая', 'Магическая'],
      effects:
        'При употреблении: 1d6 урона ядом (спасбросок Телосложения СЛ 13 для половины). При смешивании с лунной росой (собранной в полнолуние) служит основным компонентом зелья невидимости. Концентрированный экстракт может использоваться как контактный яд — нанести на оружие, при попадании 2d6 урона ядом.',
      sortOrder: 2,
    },
  });

  await prisma.herb.create({
    data: {
      name: 'Корень Вечного Сна',
      latinName: 'Radix somnus aeterna',
      rarity: 'VERY_RARE',
      discoveredAt: 'Неизвестно',
      description:
        'По легендам древних эльфов, этот корень вырастает лишь там, где умер маг, не завершивший своё великое заклинание. Его сила настолько велика, что даже прикосновение к нему без магической защиты может погрузить человека в беспробудный сон на годы. Архивы Магической Академии содержат лишь три задокументированных случая его обнаружения за последние пятьсот лет. Последний экземпляр был найден в 1198 году — его судьба неизвестна.',
      properties: ['Магическая', 'Артефактная', 'Проклятая'],
      effects:
        'Засекречено Советом Архимагов. Доступ к информации ограничен. Предположительно способен погрузить в вечный сон существо любого уровня.',
      sortOrder: 3,
    },
  });

  // тестовые данные: первые две травы открыты всем игрокам, третья — никому
  await prisma.herbAccess.createMany({
    data: playerIds.flatMap((playerId) => [
      { herbId: mint.id, playerId },
      { herbId: nightshade.id, playerId },
    ]),
  });

  console.log('✓ База данных заполнена тестовыми данными');
}

main()
  .catch((err) => {
    console.error(err);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
